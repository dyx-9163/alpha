package i18n

import (
	"fmt"
	"strings"
)

type Locale string

const (
	Zh Locale = "zh"
	En Locale = "en"
)

func Resolve(lang string) Locale {
	lang = strings.ToLower(strings.TrimSpace(lang))
	if strings.HasPrefix(lang, "en") {
		return En
	}
	return Zh
}

func Text(lang, key string, args ...any) string {
	locale := Resolve(lang)
	template := catalogs[locale][key]
	if template == "" {
		template = mysqlBackupCatalogs[locale][key]
	}
	if template == "" {
		template = catalogs[Zh][key]
	}
	if template == "" {
		template = mysqlBackupCatalogs[Zh][key]
	}
	if template == "" {
		return key
	}
	if len(args) == 0 {
		return template
	}
	return fmt.Sprintf(template, args...)
}

