// MySQLBackupErrorText resolves the stable backup/restore code through the
// shared backend catalog. Unknown codes intentionally remain machine-readable.
func MySQLBackupErrorText(lang, code string) string {
	key, ok := mysqlBackupErrorMessageKeys[code]
	if !ok {
		return code
	}
	return Text(lang, key)
}

